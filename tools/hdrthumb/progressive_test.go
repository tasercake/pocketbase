func TestInspectPrimaryJPEGScopesMarkersToFirstCodestream(t *testing.T) {
	primary := []byte{
		0xff, 0xd8,
		0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
		0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
		0x12, 0xff, 0x00, 0x34, 0xff, 0xd0, 0x56,
		0xff, 0xd9,
	}
	// Appended gain map intentionally looks progressive and has two scans.
	gainMap := []byte{
		0xff, 0xd8,
		0xff, 0xc2, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
		0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x01,
		0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x02,
		0xff, 0xd9,
	}
	data := append(append([]byte{}, primary...), gainMap...)

	info, err := InspectPrimaryJPEG(data)
	if err != nil {
		t.Fatal(err)
	}
	if info.FirstSOF != 0xc0 || info.SOSCount != 1 {
		t.Fatalf("primary info = %+v, want baseline SOF0 and one scan", info)
	}
	if info.End != len(primary) {
		t.Fatalf("primary end = %d, want %d", info.End, len(primary))
	}
}

func TestInspectPrimaryJPEGProgressiveMultipleScansAndICC(t *testing.T) {
	data := []byte{
		0xff, 0xd8,
		0xff, 0xe2, 0x00, 0x10, 'I', 'C', 'C', '_', 'P', 'R', 'O', 'F', 'I', 'L', 'E', 0, 1, 1,
		0xff, 0xc2, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00,
		0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x01,
		0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x02,
		0xff, 0xd9,
	}
	info, err := InspectPrimaryJPEG(data)
	if err != nil {
		t.Fatal(err)
	}
	if info.FirstSOF != 0xc2 || info.SOSCount != 2 || !info.HasICC || info.HasValidICC {
		t.Fatalf("primary info = %+v; tiny malformed ICC must not be considered complete", info)
	}
}

func TestExistingBaselineUltraHDRFailsProgressiveValidation(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "..", "tests", "data", "hdr", "current-photo-1.jpg"))
	if err != nil {
		t.Skipf("HDR fixture unavailable: %v", err)
	}
	info, err := ValidateProgressiveUltraHDR(data, "image/jpeg")
	if err == nil {
		t.Fatalf("baseline Ultra HDR unexpectedly passed: %+v", info)
	}
	if info.FirstSOF != 0xc0 {
		t.Fatalf("fixture first SOF = FF%02X, want FFC0", info.FirstSOF)
	}
}
